DEFAULT_ITEMS = ["SPY", "SPY_PAGE"]


class AcquisitionError(RuntimeError):
    pass


def utc_now() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0)


def iso_z(moment: dt.datetime) -> str:
    return moment.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def fetch(url: str) -> dict:
    """One GET. Returns status, final URL, selected headers and the body; raises on anything but 200."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "*/*"})
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            body = response.read(MAX_DOWNLOAD_BYTES + 1)
            status = response.status
            final_url = response.geturl()
            headers = {key.lower(): value for key, value in response.headers.items()}
    except urllib.error.HTTPError as exc:
        snippet = exc.read(300)
        raise AcquisitionError(f"GET {url} -> HTTP {exc.code} {exc.reason}; body starts {snippet!r}") from None
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise AcquisitionError(f"GET {url} failed: {exc!r}") from None
    if status != 200:
        raise AcquisitionError(f"GET {url} -> HTTP {status}; body starts {body[:300]!r}")
    if len(body) > MAX_DOWNLOAD_BYTES:
        raise AcquisitionError(f"GET {url}: response larger than {MAX_DOWNLOAD_BYTES} bytes")
    if not body:
        raise AcquisitionError(f"GET {url}: empty response body")
    declared = headers.get("content-length")
    if declared is not None and declared.isdigit() and int(declared) != len(body):
        raise AcquisitionError(f"GET {url}: truncated body ({len(body)} of {declared} bytes)")
    return {
        "http_status": status,
        "url_final": final_url,
        "content_type": headers.get("content-type"),
        "http_last_modified": headers.get("last-modified"),
        "http_date": headers.get("date"),
        "body": body,
    }


def validate(item_key: str, body: bytes, retrieval_date: str) -> dict:
    """Parse the payload completely; return the facts recorded in the manifest."""
    item = ITEMS[item_key]
    try:
        if item_key == "SPY":
            parsed = parse_ssga_daily_holdings(body, "SPY")
        elif item_key == "XIU":
            parsed = parse_ishares_holdings_csv(body, "XIU")
        else:
            page = parse_ssga_fund_sector_breakdown(body)
            total = sum((s["weight_percent"] for s in page["sectors"]), Decimal(0))
            if not Decimal("99") <= total <= Decimal("101"):
                raise HoldingsFormatError(f"sector breakdown sums to {total} percent")
            if page["as_of_date"] > retrieval_date:
                raise HoldingsFormatError(f"as-of date {page['as_of_date']} is after the retrieval date")
            return {"as_of_date_in_file": page["as_of_date"], "as_of_text_in_file": page["as_of_text"],
                    "n_sectors": len(page["sectors"]), "total_weight_percent": str(total)}
    except HoldingsFormatError as exc:
        raise AcquisitionError(f"{item_key}: file rejected: {exc}; first bytes {body[:120]!r}") from None

    summary = summarize(parsed)
    total = summary["total_percent"]
    equity = summary["percent_by_kind"].get(EQUITY, Decimal(0))
    n_equity = summary["count_by_kind"].get(EQUITY, 0)
    if not Decimal("95") <= total <= Decimal("100.5"):
        raise AcquisitionError(f"{item_key}: weights sum to {total}; expected about 100 (percent scale)")
    if n_equity < item["min_equity_lines"]:
        raise AcquisitionError(f"{item_key}: only {n_equity} equity lines (expected >= {item['min_equity_lines']})")
    if parsed["holdings_date"] > retrieval_date:
        raise AcquisitionError(f"{item_key}: holdings date {parsed['holdings_date']} is after retrieval {retrieval_date}")
    return {
        "as_of_date_in_file": parsed["holdings_date"],
        "as_of_text_in_file": parsed["holdings_date_text"],
        "publication_date": parsed["publication_date"],
        "n_lines": len(parsed["lines"]),
        "n_equity_lines": n_equity,
        "equity_weight_percent": str(equity),
        "total_weight_percent": str(total),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--item", action="append", choices=sorted(ITEMS), help="default: SPY and SPY_PAGE")
    parser.add_argument("--from-file", metavar="PATH",
                        help="register a file downloaded by hand in a web browser (exactly one --item)")
    parser.add_argument("--retrieved-at", metavar="UTC_ISO",
                        help="with --from-file: when the file was downloaded, e.g. 2026-11-14T22:30:01Z")
    parser.add_argument("--http-status", type=int, help="with --from-file: HTTP status observed, if known")
    parser.add_argument("--method", help="with --from-file: how the file was obtained (free text)")
    parser.add_argument("--allow-automated", action="append", default=[], choices=sorted(ITEMS), metavar="ITEM",
                        help="automated download of an item whose issuer terms require permission (you hold it)")
    args = parser.parse_args()

    items = args.item or DEFAULT_ITEMS
    if len(set(items)) != len(items):
        parser.error("duplicate --item")
    if args.from_file and len(items) != 1:
        parser.error("--from-file needs exactly one --item")
    if args.from_file and not args.retrieved_at:
        parser.error("--from-file needs --retrieved-at (UTC time of the manual download)")
    if (args.retrieved_at or args.http_status or args.method) and not args.from_file:
        parser.error("--retrieved-at/--http-status/--method only apply to --from-file")

    # Pre-flight: refuse before any network request if an item may not be fetched automatically.
    if not args.from_file:
        blocked = [key for key in items if not ITEMS[key]["automated_download"] and key not in args.allow_automated]
        if blocked:
            print("ACQUISITION FAILED - nothing was requested or written.", file=sys.stderr)
            print(f"  - automated download is disabled for: {', '.join(blocked)}\n{BLACKROCK_NOTICE}", file=sys.stderr)
            return 2

    staged = []
    errors = []
    for index, key in enumerate(items):
        item = ITEMS[key]
        try:
            if args.from_file:
                source_path = Path(args.from_file).expanduser()
                body = source_path.read_bytes()
                try:
                    moment = dt.datetime.fromisoformat(args.retrieved_at.replace("Z", "+00:00"))
                except ValueError:
                    raise AcquisitionError(f"--retrieved-at is not an ISO timestamp: {args.retrieved_at!r}") from None
                if moment.tzinfo is None:
                    raise AcquisitionError("--retrieved-at must carry a timezone (use a trailing Z for UTC)")
                if moment > utc_now() + dt.timedelta(minutes=5):
                    raise AcquisitionError("--retrieved-at is in the future")
                meta = {"http_status": args.http_status, "url_final": None, "content_type": None,
                        "http_last_modified": None, "http_date": None,
                        "retrieval_method": args.method or "manual web-browser download registered with --from-file"}
            else:
                if index:
                    time.sleep(1.0)
                response = fetch(item["url"])
                body = response.pop("body")
                moment = utc_now()
                meta = dict(response, retrieval_method=f"HTTP GET by acquire_holdings.py (User-Agent: {USER_AGENT})")
            retrieval_date = moment.astimezone(dt.timezone.utc).date().isoformat()
            facts = validate(key, body, retrieval_date)
            target = RAW_DIR / item["raw_subdir"] / f"{key}_{retrieval_date}.{item['ext']}"
            digest = sha256_bytes(body)
            already = target.exists()
            if already and sha256_file(target) != digest:
                raise AcquisitionError(
                    f"{key}: {rel(target)} already exists with different content. Raw files are never "
                    "modified; a second, different snapshot on the same UTC date is refused.")
            record = {
                "source_id": f"{item['source_id_prefix']}_{retrieval_date}",
                "kind": item["kind"],
                "item": key,
                "fund_id": item["fund_id"],
                "publisher": item["publisher"],
                "title": item["title"],
                "path": rel(target),
                "url_requested": item["url"],
                "url_final": meta["url_final"],
                "product_page": item["product_page"],
                "http_status": meta["http_status"],
                "content_type": meta["content_type"],
                "http_last_modified": meta["http_last_modified"],
                "http_date": meta["http_date"],
                "retrieval_method": meta["retrieval_method"],
                "retrieved_at_utc": iso_z(moment),
                "retrieval_date": retrieval_date,
                "bytes": len(body),
                "sha256": digest,
            }
            record.update(facts)
            staged.append((key, target, body, record, already))
        except (AcquisitionError, OSError) as exc:
            errors.append(str(exc))

    if errors:
        print("ACQUISITION FAILED - nothing was written.", file=sys.stderr)
        for message in errors:
            print(f"  - {message}", file=sys.stderr)
        return 2

    manifest = load_json(RAW_MANIFEST) if RAW_MANIFEST.exists() else {
        "schema_version": SCHEMA_VERSION,
        "note": ("One record per raw file retrieved by data/scripts/acquire_*.py. Raw files live under data/raw/ "
                 "(git-ignored) and are never modified after retrieval; this manifest is the committed record "
                 "of their URL, retrieval time, size and SHA-256."),
        "files": [],
    }
    by_id = {entry["source_id"]: entry for entry in manifest["files"]}
    for key, target, body, record, already in staged:
        if not already:
            write_bytes_atomic(target, body, overwrite=False)
            os.chmod(target, stat.S_IRUSR | stat.S_IRGRP | stat.S_IROTH)
        previous = by_id.get(record["source_id"])
        if previous and previous["sha256"] == record["sha256"]:
            state = "unchanged (already in the manifest; manifest record kept as first recorded)"
        else:
            by_id[record["source_id"]] = record
            state = "registered" if already else "written"
        print(f"{key}: {state}: {record['path']}")
        print(f"    source_id={record['source_id']}  http_status={record['http_status']}  bytes={record['bytes']}")
        print(f"    sha256={record['sha256']}")
        print(f"    retrieved_at_utc={record['retrieved_at_utc']}  as-of date printed in file="
              f"{record['as_of_date_in_file']} ({record['as_of_text_in_file']!r})")
        if "n_equity_lines" in record:
            print(f"    lines={record['n_lines']}  equity lines={record['n_equity_lines']}  "
                  f"equity weight={record['equity_weight_percent']}%  all lines={record['total_weight_percent']}%")
    manifest["files"] = sorted(by_id.values(), key=lambda entry: (entry["kind"], entry["source_id"]))
    write_bytes_atomic(RAW_MANIFEST, dump_json(manifest), overwrite=True)
    print(f"manifest updated: {rel(RAW_MANIFEST)} ({len(manifest['files'])} record(s))")

    registered_funds = {entry["item"] for entry in manifest["files"]}
    if "XIU" not in registered_funds:
        print("\nNOTE: no XIU holdings file is registered yet.\n" + BLACKROCK_NOTICE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
