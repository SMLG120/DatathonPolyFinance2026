#!/usr/bin/env python3
"""Acquire issuer-published ETF holdings files (standard library only).

Only the funds the core demos need are configured: SPY (State Street) and
XIU (BlackRock iShares Canada). QQQ and ESGV are deliberately NOT fetched
(LEAD_DECISIONS D7: ESGV demonstrates unknown coverage).

    # SPY holdings + the SPY product page (issuer's fund-level sector breakdown)
    python3 -I data/scripts/acquire_holdings.py

    # XIU: BlackRock's terms forbid automated copying without permission but
    # allow downloads with a normal web browser. Download the holdings CSV by
    # hand from the product page, then register it:
    python3 -I data/scripts/acquire_holdings.py --item XIU \
        --from-file ~/Downloads/XIU_holdings.csv --retrieved-at 2026-11-14T22:30:01Z

What it guarantees
* Raw files go to data/raw/<subdir>/<ITEM>_<retrieval-date>.<ext> (retrieval
  date = UTC date), are written atomically, set read-only and never
  overwritten. data/raw/ is git-ignored.
* Every file is fully parsed and sanity-checked BEFORE anything is written.
  Any failure (HTTP status, layout, weight scale, future as-of date) aborts
  the whole run with a non-zero exit code: no partial output.
* data/manifests/raw_files_manifest.json records URL, HTTP status, retrieval
  timestamp (UTC), byte size, SHA-256 and the as-of date printed INSIDE the
  file, which is kept separate from the retrieval date. The issuers print no
  publication date, so publication_date stays null; the HTTP Last-Modified
  header is recorded as server metadata only.
"""
