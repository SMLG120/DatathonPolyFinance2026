const listeners = new Set<() => void>();
let locale: Locale = "en";
let hydrated = false;

function emitChange() {
  for (const listener of listeners) listener();
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function getSnapshot(): Locale {
  return locale;
}

/** English is the default. The stored preference is read only after hydration. */
export function useLocale(): readonly [Locale, (next: Locale) => void] {
  const current = useSyncExternalStore(subscribe, getSnapshot, () => "en" as Locale);

  useEffect(() => {
    if (hydrated) return;
    hydrated = true;
    try {
      const saved = window.localStorage.getItem("byb.locale");
      if (saved === "en" || saved === "fr") {
        locale = saved;
        emitChange();
      }
      document.documentElement.lang = locale;
    } catch {
      // The interface remains usable in browsers that block local storage.
    }
  }, []);

  const setLocale = useCallback((next: Locale) => {
    if (locale === next) return;
    locale = next;
    try {
      window.localStorage.setItem("byb.locale", next);
      document.documentElement.lang = next;
    } catch {
      // Persistence is best-effort; the selected language still applies in memory.
    }
    emitChange();
  }, []);

  return [current, setLocale] as const;
}

/** Translate only app-authored catalog text. User, API and evidence content is passed through untouched. */
export function t(message: string): string {
  const decoded = message
    .replace(/&amp;/g, "&")
    .replace(/&apos;/g, "'")
    .replace(/&rsquo;/g, "’")
    .replace(/&lsquo;/g, "‘")
    .replace(/&ldquo;/g, "“")
    .replace(/&rdquo;/g, "”")
    .replace(/&nbsp;/g, " ");
  if (locale === "en") return decoded;
  return translations[message] ?? translations[decoded] ?? decoded;
}

/**
 * Translate a catalog template that holds named values, e.g. tf("Evidence for {rule}", { rule }). The whole template
 * is looked up (so a translation can reorder the words around the values), then each {name} is replaced. Values are
 * inserted as given: numbers and names coming from the API or the user are never translated.
 */
export function tf(template: string, values: Record<string, string | number>): string {
  return t(template).replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}

export function getLocale(): Locale {
  return locale;
}

export function resetLocaleRuntimeForTests(): void {
  locale = "en";
  hydrated = false;
  if (typeof document !== "undefined") document.documentElement.lang = "en";
  emitChange();
}
